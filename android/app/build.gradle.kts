// Nombre del APK generado: en vez de app-release.apk queda
// DescVideos-1.0.0-release.apk, para no confundir versiones al compartirlo.
androidComponents {
    onVariants { variant ->
        variant.outputs.forEach { output ->
            if (output is com.android.build.api.variant.impl.VariantOutputImpl) {
                val version = output.versionName.orNull ?: "sinversion"
                output.outputFileName.set("DescVideos-$version-${variant.name}.apk")
            }
        }
    }
}

